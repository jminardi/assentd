const (
	exUnavailable = 69
	exTempfail    = 75
	exNoperm      = 77
)

func cliErr(format string, a ...any) {
	fmt.Fprintf(os.Stderr, "assentd: "+format+"\n", a...)
}

// ---- argument parsing: options may come before or after positionals, as --opt value or --opt=value.

type optSpec struct {
	takesValue, repeat bool
}

type parsedArgs struct {
	opts map[string][]string
	pos  []string
}

func (p *parsedArgs) get(name string) string {
	if v := p.opts[name]; len(v) > 0 {
		return v[len(v)-1]
	}
	return ""
}

func (p *parsedArgs) has(name string) bool { _, ok := p.opts[name]; return ok }

func (p *parsedArgs) int(name string, def int) int {
	s := p.get(name)
	if s == "" {
		return def
	}
	n, err := strconv.Atoi(s)
	if err != nil {
		cliErr("--%s needs a number", name)
		os.Exit(2)
	}
	return n
}

func parseArgs(args []string, spec map[string]optSpec, aliases map[string]string) (*parsedArgs, error) {
	p := &parsedArgs{opts: map[string][]string{}}
	for i := 0; i < len(args); i++ {
		a := args[i]
		if !strings.HasPrefix(a, "-") || a == "-" {
			p.pos = append(p.pos, a)
			continue
		}
		name, val, hasVal := strings.Cut(strings.TrimLeft(a, "-"), "=")
		if !strings.HasPrefix(a, "--") {
			if full, ok := aliases[a]; ok {
				name = full
			} else {
				return nil, fmt.Errorf("unknown option %s", a)
			}
			hasVal = false
		}
		s, ok := spec[name]
		if !ok {
			return nil, fmt.Errorf("unknown option --%s", name)
		}
		if s.takesValue && !hasVal {
			if i+1 >= len(args) {
				return nil, fmt.Errorf("--%s needs a value", name)
			}
			i++
			val = args[i]
		} else if !s.takesValue && hasVal {
			return nil, fmt.Errorf("--%s takes no value", name)
		}
		if _, seen := p.opts[name]; seen && !s.repeat && s.takesValue {
			p.opts[name] = nil
		}
		p.opts[name] = append(p.opts[name], val)
	}
	return p, nil
}

var (
	commonOpts = map[string]optSpec{"reason": {true, false}, "timeout": {true, false}}
	policyOpts = map[string]optSpec{"description": {true, false}, "modes": {true, false}, "hosts": {true, false},
		"auth-header": {true, false}, "max-ttl": {true, false}, "fill-origin": {true, true}}
)

func merge(maps ...map[string]optSpec) map[string]optSpec {
	out := map[string]optSpec{}
	for _, m := range maps {
		for k, v := range m {
			out[k] = v
		}
	}
	return out
}

// ---- talking to the daemon

func connect() *net.UnixConn {
	c, err := net.DialUnix("unix", nil, &net.UnixAddr{Name: sockPath, Net: "unix"})
	if err != nil {
		cliErr("cannot reach the vault daemon at %s: %v", sockPath, err)
		os.Exit(exUnavailable)
	}
	return c
}

func call(msg map[string]any) map[string]any {
	c := connect()
	defer c.Close()
	data, _ := json.Marshal(msg)
	c.Write(append(data, '\n'))
	r := bufio.NewReader(c)
	line, err := readLine(r, 64<<20)
	var reply map[string]any
	if err != nil || json.Unmarshal(line, &reply) != nil {
		cliErr("daemon closed the connection without replying")
		os.Exit(exUnavailable)
	}
	return reply
}

func fmtTTL(seconds float64) string {
	s := int(seconds)
	if s >= 3600 && s%3600 == 0 {
		return fmt.Sprintf("%dh", s/3600)
	}
	if s >= 60 {
		return fmt.Sprintf("%dm", s/60)
	}
	return fmt.Sprintf("%ds", s)
}

// request sends a request/deposit op, reports what has to happen on the phone, and returns the
// final reply (or exits).
func request(msg map[string]any, op string) map[string]any {
	cwd, _ := os.Getwd()
	msg["op"] = op
	msg["cwd"] = cwd
	c := connect()
	data, _ := json.Marshal(msg)
	c.Write(append(data, '\n'))
	// Ctrl-C or a kill while waiting withdraws the request (the daemon sees the socket close).
	sigs := make(chan os.Signal, 1)
	signal.Notify(sigs, syscall.SIGINT, syscall.SIGTERM, syscall.SIGHUP)
	go func() {
		<-sigs
		c.Close()
		cliErr("cancelled")
		os.Exit(exTempfail)
	}()
	r := bufio.NewReader(c)
	var reply map[string]any
	for {
		line, err := readLine(r, 64<<20)
		if err != nil {
			break
		}
		reply = nil
		if json.Unmarshal(line, &reply) != nil {
			break
		}
		if _, ok := reply["pending"]; ok {
			names := strs(reply["names"])
			newNames := strs(reply["new"])
			what := "approval of " + strings.Join(names, ", ")
			if len(newNames) > 0 {
				what = "entry of " + strings.Join(newNames, ", ")
			}
			cliErr("waiting for %s on your phone: %v", what, reply["url"])
			continue
		}
		if _, ok := reply["pending_deposit"]; ok {
			cliErr("sealed %v chars into the phone inbox; waiting for it to be accepted: %v", reply["length"], reply["url"])
			continue
		}
		break
	}
	signal.Stop(sigs)
	c.Close()
	if ok, _ := reply["ok"].(bool); !ok {
		msg := "no reply from daemon"
		if e, ok := reply["error"].(string); ok {
			msg = e
		}
		cliErr("%s", msg)
		switch reply["status"] {
		case "denied":
			os.Exit(exNoperm)
		case "expired", "cancelled", "timeout":
			os.Exit(exTempfail)
		}
		os.Exit(1)
	}
	if ttl, _ := reply["ttl"].(float64); ttl > 0 {
		cliErr("approved; grant reusable by this session for %s", fmtTTL(ttl))
	}
	return reply
}

func strs(v any) []string {
	list, _ := v.([]any)
	out := []string{}
	for _, x := range list {
		if s, ok := x.(string); ok {
			out = append(out, s)
		}
	}
	return out
}

func splitList(parts []string) []string {
	var out []string
	for _, part := range parts {
		for _, n := range strings.Split(part, ",") {
			if n = strings.TrimSpace(n); n != "" {
				out = append(out, n)
			}
		}
	}
	return out
}

func checkCommon(p *parsedArgs) {
	if p.get("reason") == "" {
		cliErr("--reason is required (it is shown on the phone)")
		os.Exit(2)
	}
}

func proposalFrom(p *parsedArgs) map[string]any {
	modes := splitList([]string{p.get("modes")})
	hosts := []string{}
	for _, h := range splitList([]string{p.get("hosts")}) {
		hosts = append(hosts, strings.ToLower(h))
	}
	origins := []string{}
	for _, o := range splitList(p.opts["fill-origin"]) {
		origins = append(origins, strings.TrimRight(strings.ToLower(o), "/"))
	}
	if len(modes) == 0 {
		modes = []string{"command"}
		if len(hosts) > 0 {
			modes = []string{"http"}
		} else if len(origins) > 0 {
			modes = []string{"fill"}
		}
	}
	prop := map[string]any{"description": p.get("description"), "modes": modes, "hosts": hosts, "max_ttl": p.int("max-ttl", 900)}
	if contains(modes, "http") {
		hdr := p.get("auth-header")
		if hdr == "" {
			hdr = "Authorization: Bearer {}"
		}
		prop["http"] = map[string]any{"header": hdr}
	}
	if len(origins) > 0 {
		prop["fill"] = map[string]any{"origins": origins}
	}
	return prop
}

// ---- commands

func cmdList(args []string) int {
	if len(args) > 0 {
		cliErr("list takes no arguments")
		return 2
	}
	r := call(map[string]any{"op": "list"})
	if ok, _ := r["ok"].(bool); !ok {
		cliErr("%v", r["error"])
		return 1
	}
	if e, _ := r["enrolled"].(bool); !e {
		fmt.Println("vault is not enrolled yet")
	}
	secrets, _ := r["secrets"].([]any)
	if len(secrets) == 0 {
		fmt.Printf("no secrets stored; add them at %v/add\n", r["url"])
	}
	for _, x := range secrets {
		m, _ := x.(map[string]any)
		hosts := strs(m["hosts"])
		line := fmt.Sprintf("%-28v max %-4s modes=%s", m["name"], fmtTTL(num(m["max_ttl"])), strings.Join(strs(m["modes"]), ","))
		if len(hosts) > 0 {
			line += "  hosts=" + strings.Join(hosts, ",")
		}
		if fp, ok := m["fill"].(map[string]any); ok {
			line += "  fill=" + strings.Join(strs(fp["origins"]), ",")
		}
		if hp, ok := m["http"].(map[string]any); ok {
			var limits []string
			if ms := strs(hp["methods"]); len(ms) > 0 {
				limits = append(limits, "methods="+strings.Join(ms, ","))
			}
			if ps := strs(hp["paths"]); len(ps) > 0 {
				limits = append(limits, "paths="+strings.Join(ps, ","))
			}
			if len(limits) > 0 {
				line += "  http:" + strings.Join(limits, " ")
			}
		}
		fmt.Printf("%s  %v\n", line, m["description"])
	}
	return 0
}

func num(v any) float64 {
	f, _ := v.(float64)
	return f
}

func cmdStatus(args []string) int {
	r := call(map[string]any{"op": "status"})
	grants, _ := r["grants"].([]any)
	pending, _ := r["pending"].([]any)
	if len(grants) == 0 && len(pending) == 0 {
		fmt.Println("no active grants, nothing pending")
	}
	t := float64(time.Now().Unix())
	for _, x := range grants {
		g, _ := x.(map[string]any)
		fmt.Printf("grant   %-30s %-7v %s left\n", strings.Join(strs(g["names"]), ","), g["mode"], fmtTTL(max(0, num(g["expires"])-t)))
	}
	for _, x := range pending {
		p, _ := x.(map[string]any)
		fmt.Printf("pending %-30s %v\n", strings.Join(strs(p["names"]), ","), p["mode"])
	}
	return 0
}

