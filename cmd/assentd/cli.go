func cmdRun(args []string) int {
	i := -1
	for j, a := range args {
		if a == "--" {
			i = j
			break
		}
	}
	if i < 0 || i == len(args)-1 {
		cliErr("nothing to run; usage: assentd run --need NAME --reason WHY -- command [args...]")
		return 2
	}
	command := args[i+1:]
	p, err := parseArgs(args[:i], merge(commonOpts, map[string]optSpec{"need": {true, true}}), nil)
	if err != nil {
		cliErr("%v", err)
		return 2
	}
	checkCommon(p)
	needs := splitList(p.opts["need"])
	if len(needs) == 0 || len(p.pos) > 0 {
		cliErr("usage: assentd run --need NAME[,NAME] --reason WHY -- command [args...]")
		return 2
	}
	reply := request(map[string]any{"needs": needs, "reason": p.get("reason"), "argv": command, "timeout": p.int("timeout", 300),
		"mode": "command"}, "request")
	vals, _ := reply["values"].(map[string]any)
	values := map[string]string{}
	for k, x := range vals {
		values[k], _ = x.(string)
	}
	scrubber := newScrubber(values, nil, func(s string) { cliErr("%s", s) })
	env := os.Environ()
	for k, x := range values {
		env = append(env, k+"="+x)
	}
	clear(values)
	return runScrubbed(command, env, scrubber)
}

func runScrubbed(command, env []string, s *Scrubber) int {
	cmd := exec.Command(command[0], command[1:]...)
	cmd.Env = env
	cmd.Stdin = os.Stdin
	stdout, _ := cmd.StdoutPipe()
	stderr, _ := cmd.StderrPipe()
	if err := cmd.Start(); err != nil {
		cliErr("cannot run %s: %v", command[0], err)
		return 127
	}
	sigs := make(chan os.Signal, 4)
	signal.Notify(sigs, syscall.SIGINT, syscall.SIGTERM, syscall.SIGHUP)
	go func() {
		for sig := range sigs {
			cmd.Process.Signal(sig)
		}
	}()
	var wg sync.WaitGroup
	for _, pair := range [][2]any{{stdout, os.Stdout}, {stderr, os.Stderr}} {
		wg.Add(1)
		go func(r io.Reader, w io.Writer) {
			defer wg.Done()
			s.pump(r, w)
		}(pair[0].(io.Reader), pair[1].(io.Writer))
	}
	wg.Wait()
	err := cmd.Wait()
	signal.Stop(sigs)
	if err == nil {
		return 0
	}
	var ee *exec.ExitError
	if errors.As(err, &ee) {
		if ws, ok := ee.Sys().(syscall.WaitStatus); ok && ws.Signaled() {
			return 128 + int(ws.Signal())
		}
		return ee.ExitCode()
	}
	return 1
}

func cmdHTTP(args []string) int {
	spec := merge(commonOpts, map[string]optSpec{"secret": {true, true}, "request": {true, false}, "header": {true, true},
		"data": {true, false}, "data-file": {true, false}, "json": {true, false}, "include": {}, "output": {true, false}, "fail": {}})
	p, err := parseArgs(args, spec, map[string]string{"-X": "request", "-H": "header", "-i": "include", "-o": "output"})
	if err != nil {
		cliErr("%v", err)
		return 2
	}
	checkCommon(p)
	if len(p.pos) != 1 {
		cliErr("give exactly one URL")
		return 2
	}
	url := p.pos[0]
	secret := splitList(p.opts["secret"])
	if len(secret) != 1 {
		cliErr("name exactly one secret with --secret NAME (one secret per request)")
		return 2
	}
	headers := [][]string{}
	for _, h := range p.opts["header"] {
		name, value, ok := strings.Cut(h, ":")
		if !ok || strings.TrimSpace(name) == "" {
			cliErr("bad header %q; use 'Name: value'", h)
			return 2
		}
		if strings.Contains(value, placeholderTag) {
			cliErr("secrets don't go in -H headers: each secret's policy names its header. Use --secret NAME")
			return 2
		}
		headers = append(headers, []string{strings.TrimSpace(name), strings.TrimSpace(value)})
	}
	n := 0
	for _, k := range []string{"data", "data-file", "json"} {
		if p.has(k) {
			n++
		}
	}
	if n > 1 {
		cliErr("use only one of --data, --data-file, --json")
		return 2
	}
	var body []byte
	switch {
	case p.has("data"):
		body = []byte(p.get("data"))
	case p.has("json"):
		body = []byte(p.get("json"))
		hasCT := false
		for _, h := range headers {
			hasCT = hasCT || strings.EqualFold(h[0], "content-type")
		}
		if !hasCT {
			headers = append(headers, []string{"Content-Type", "application/json"})
		}
	case p.has("data-file"):
		f := p.get("data-file")
		if f == "-" {
			body, err = io.ReadAll(os.Stdin)
		} else {
			body, err = os.ReadFile(f)
		}
		if err != nil {
			cliErr("cannot read %s: %v", f, err)
			return 2
		}
	}
	if strings.Contains(url, placeholderTag) || strings.Contains(string(body), placeholderTag) {
		cliErr("secrets only go in the header their policy names, never in the URL or body; use --secret NAME")
		return 2
	}
	method := strings.ToUpper(p.get("request"))
	if method == "" {
		method = "GET"
		if len(body) > 0 {
			method = "POST"
		}
	}
	target := map[string]any{"method": method, "url": url, "headers": headers, "use": secret,
		"body_b64": base64.StdEncoding.EncodeToString(body)}
	r := request(map[string]any{"needs": secret, "reason": p.get("reason"), "argv": []string{"assentd", "http", method, url},
		"timeout": p.int("timeout", 300), "mode": "http", "target": target}, "request")
	status := int(num(r["status"]))
	reason, _ := r["reason"].(string)
	line := strings.TrimRight(fmt.Sprintf("HTTP %d %s", status, reason), " ")
	if t, _ := r["truncated"].(bool); t {
		line += " (body truncated)"
	}
	cliErr("%s", line)
	data, _ := base64.StdEncoding.DecodeString(fmt.Sprint(r["body_b64"]))
	out := io.Writer(os.Stdout)
	if o := p.get("output"); o != "" {
		f, err := os.Create(o)
		if err != nil {
			cliErr("cannot write %s: %v", o, err)
			return 1
		}
		defer f.Close()
		out = f
	}
	if p.has("include") {
		fmt.Fprintf(out, "HTTP %d %s\r\n", status, reason)
		hdrs, _ := r["headers"].([]any)
		for _, h := range hdrs {
			kv := strs(h)
			if len(kv) == 2 {
				fmt.Fprintf(out, "%s: %s\r\n", kv[0], kv[1])
			}
		}
		io.WriteString(out, "\r\n")
	}
	out.Write(data)
	if p.has("fail") && status >= 400 {
		return 22
	}
	return 0
}

func cmdFill(args []string) int {
	p, err := parseArgs(args, merge(commonOpts, map[string]optSpec{"tab": {true, false}}), nil)
	if err != nil {
		cliErr("%v", err)
		return 2
	}
	checkCommon(p)
	if len(p.pos) != 1 {
		cliErr("usage: assentd fill NAME --reason WHY [--tab ID]")
		return 2
	}
	name := p.pos[0]
	msg := map[string]any{"needs": []string{name}, "reason": p.get("reason"), "argv": []string{"assentd", "fill", name},
		"timeout": p.int("timeout", 300), "mode": "fill"}
	if p.has("tab") {
		msg["tab"] = p.int("tab", 0)
	}
	r := request(msg, "request")
	cliErr("filled %s into the password field on %v", name, r["origin"])
	return 0
}

func cmdAsk(args []string) int {
	p, err := parseArgs(args, merge(commonOpts, policyOpts, map[string]optSpec{"replace": {}}), nil)
	if err != nil {
		cliErr("%v", err)
		return 2
	}
	checkCommon(p)
	if len(p.pos) != 1 || (p.get("description") == "" && !p.has("replace")) {
		cliErr("usage: assentd ask NAME --description D --reason R (the description is shown on the phone)")
		return 2
	}
	name := p.pos[0]
	request(map[string]any{"needs": []string{name}, "reason": p.get("reason"), "argv": []string{"assentd", "ask", name},
		"timeout": p.int("timeout", 300), "mode": "store", "replace": p.has("replace"),
		"proposals": map[string]any{name: proposalFrom(p)}}, "request")
	cliErr("%s saved in the vault", name)
	return 0
}

func depositOp(p *parsedArgs, extra map[string]any) int {
	msg := map[string]any{"name": p.pos[0], "reason": p.get("reason"), "replace": p.has("replace"), "wait": !p.has("no-wait"),
		"timeout": p.int("timeout", 300), "proposal": proposalFrom(p)}
	for k, v := range extra {
		msg[k] = v
	}
	r := request(msg, "deposit")
	if r["status"] == "accepted" {
		cliErr("%s accepted into the vault", p.pos[0])
	} else {
		cliErr("the deposit is waiting on the phone")
	}
	return 0
}

var depositOpts = map[string]optSpec{"replace": {}, "no-wait": {}}

func cmdGenerate(args []string) int {
	p, err := parseArgs(args, merge(commonOpts, policyOpts, depositOpts, map[string]optSpec{"length": {true, false}, "charset": {true, false}}), nil)
	if err != nil {
		cliErr("%v", err)
		return 2
	}
	checkCommon(p)
	if len(p.pos) != 1 || (p.get("description") == "" && !p.has("replace")) {
		cliErr("usage: assentd generate NAME --description D --reason R")
		return 2
	}
	cs := p.get("charset")
	if cs == "" {
		cs = "alnum"
	}
	return depositOp(p, map[string]any{"generate": map[string]any{"length": p.int("length", 32), "charset": cs}})
}

// extract pulls the secret out of piped command output. Never echoes the input on failure.
func extract(data string, p *parsedArgs) (string, string) {
	if f := p.get("json-field"); f != "" {
		var node any
		if json.Unmarshal([]byte(data), &node) != nil {
			return "", fmt.Sprintf("could not find %q in the JSON input", f)
		}
		for _, part := range strings.Split(f, ".") {
			switch n := node.(type) {
			case []any:
				i, err := strconv.Atoi(part)
				if err != nil || i < 0 || i >= len(n) {
					return "", fmt.Sprintf("could not find %q in the JSON input", f)
				}
				node = n[i]
			case map[string]any:
				x, ok := n[part]
				if !ok {
					return "", fmt.Sprintf("could not find %q in the JSON input", f)
				}
				node = x
			default:
				return "", fmt.Sprintf("could not find %q in the JSON input", f)
			}
		}
		switch n := node.(type) {
		case string:
			return n, ""
		case float64:
			return strconv.FormatFloat(n, 'f', -1, 64), ""
		}
		return "", fmt.Sprintf("%q is not a string or number", f)
	}
	if rx := p.get("regex"); rx != "" {
		re, err := regexp.Compile(rx)
		if err != nil {
			return "", "bad regex: " + err.Error()
		}
		m := re.FindStringSubmatch(data)
		if m == nil {
			return "", "regex did not match the input"
		}
		if len(m) > 1 {
			return m[1], ""
		}
		return m[0], ""
	}
	return strings.TrimSpace(data), ""
}

func cmdDeposit(args []string) int {
	p, err := parseArgs(args, merge(commonOpts, policyOpts, depositOpts, map[string]optSpec{"json-field": {true, false}, "regex": {true, false}}), nil)
	if err != nil {
		cliErr("%v", err)
		return 2
	}
	checkCommon(p)
	if len(p.pos) != 1 || (p.get("description") == "" && !p.has("replace")) {
		cliErr("usage: some-command | assentd deposit NAME --description D --reason R")
		return 2
	}
	if term.IsTerminal(int(os.Stdin.Fd())) {
		cliErr("pipe the secret in, e.g.  some-command | assentd deposit NAME --json-field key ...")
		return 2
	}
	data, err := io.ReadAll(io.LimitReader(os.Stdin, 16<<20))
	if err != nil {
		cliErr("cannot read stdin: %v", err)
		return 1
	}
	value, problem := extract(string(data), p)
	if problem != "" || value == "" {
		if problem == "" {
			problem = "input was empty"
		}
		cliErr("%s", problem)
		return 1
	}
	return depositOp(p, map[string]any{"value": value, "source": "piped from a command on the Mac"})
}

func runCLI(args []string) int {
	if len(args) == 0 || args[0] == "-h" || args[0] == "--help" || args[0] == "help" {
		fmt.Print(cliUsage)
		if len(args) == 0 {
			return 2
		}
		return 0
	}
	cmds := map[string]func([]string) int{"list": cmdList, "status": cmdStatus, "revoke": cmdRevoke, "run": cmdRun,
		"http": cmdHTTP, "fill": cmdFill, "ask": cmdAsk, "generate": cmdGenerate, "deposit": cmdDeposit}
	f, ok := cmds[args[0]]
	if !ok {
		names := keys(cmds)
		sort.Strings(names)
		cliErr("unknown command %q (commands: %s; see assentd --help)", args[0], strings.Join(names, ", "))
		return 2
	}
	return f(args[1:])
}
